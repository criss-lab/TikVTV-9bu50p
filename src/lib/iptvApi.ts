function genLogoUrl(name: string): string {
  const colors = ['1a1a2e', '16213e', '0f3460', '1b1b2f', '2d1b69', '1a2744'];
  const c = colors[name.charCodeAt(0) % colors.length];
  const initials = encodeURIComponent((name || 'TV').replace(/[^a-zA-Z0-9 ]/g, '').trim().slice(0, 2).toUpperCase() || 'TV');
  return `https://ui-avatars.com/api/?name=${initials}&background=${c}&color=f59e0b&size=128&bold=true&font-size=0.4`;
}

function parseM3U(text: string, sourceTag: string): IPTVChannel[] {
  const lines    = text.split('\n');
  const channels: IPTVChannel[] = [];
  let   idx      = 0;

  while (idx < lines.length) {
    const line = lines[idx].trim();
    if (line.startsWith('#EXTINF:')) {
      const nextLine = (lines[idx + 1] || '').trim();
      if (nextLine && !nextLine.startsWith('#') && browserHls(nextLine)) {
        // Skip YouTube / Twitch
        if (nextLine.includes('youtube.com') || nextLine.includes('twitch.tv') || nextLine.includes('youtu.be')) {
          idx += 2;
          continue;
        }

        const tvgName    = line.match(/tvg-name="([^"]+)"/);
        const logoMatch  = line.match(/tvg-logo="([^"]+)"/);
        const groupMatch = line.match(/group-title="([^"]+)"/);
        const idMatch    = line.match(/tvg-id="([^"]*)"/);
        const countryM   = line.match(/tvg-country="([^"]*)"/);
        const langM      = line.match(/tvg-language="([^"]*)"/);

        // Name: prefer tvg-name, fall back to comma suffix
        const comma   = line.lastIndexOf(',');
        const rawName = comma !== -1
          ? line.slice(comma + 1).replace(/[⓪①②③④⑤⑥⑦⑧⑨🅷🅳ⓢⓣⓨ]/g, '').replace(/\s*\[.*?\]\s*/g, '').trim()
          : '';
        const name = (tvgName?.[1] || rawName || `Channel-${channels.length}`).trim();

        if (!name || name.length < 2) { idx += 2; continue; }

        const rawId  = (idMatch?.[1] || '').trim();
        const cc     = (countryM?.[1] || '').split(';')[0].trim().toUpperCase().slice(0, 2);
        const id     = rawId
          ? rawId.toLowerCase().replace(/\s+/g, '-')
          : `${sourceTag}-${name.toLowerCase().replace(/[^a-z0-9]/g, '-').slice(0, 36)}-${channels.length}`;

        const logo = (logoMatch?.[1] || '').startsWith('http') ? logoMatch![1] : genLogoUrl(name);

        channels.push({
          id,
          name,
          logo,
          country:     cc || 'INT',
          countryCode: cc || 'INT',
          languages:   langM?.[1] ? [langM[1].toLowerCase()] : [],
          categories:  [normalizeCategory(groupMatch?.[1] || 'general')],
          streamUrl:   nextLine,
          alt_names:   [],
        });
        idx += 2;
        continue;
      }
    }
    idx++;
  }
  return channels;
}

async function fetchM3U(url: string, tag: string): Promise<IPTVChannel[]> {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(5_000) });
    if (!res.ok) return [];
    const text = await res.text();
    if (!text.includes('#EXTINF')) return [];
    const parsed = parseM3U(text, tag);
    console.log(`[IPTV] ${tag}: ${parsed.length} channels`);
    return parsed;
  } catch (e) {
    console.warn(`[IPTV] ${tag} failed:`, e);
    return [];
  }
}

// Primary catalogue is returned immediately. Optional playlists are ingested in the
// background in small bounded batches; no viewer waits for 2,000 network calls.
let backgroundRefresh: Promise<void> | null = null;
const sourceHealth = new Map<string, number>();
const MAX_SOURCE_BYTES = 8 * 1024 * 1024;
// Discover approved, configured public playlists periodically while the frontend is open.
// The timer is installed once, pauses in hidden tabs, and never overlaps an ingestion run.
// Keep the fast approved API independent of the slower optional playlist crawl.
// A slow source must never delay publishing channels already returned by the API.
let approvedRefresh: Promise<void> | null = null;
function refreshApprovedCatalogue(): void {
  if (approvedRefresh) return;
  approvedRefresh = fetchApprovedCatalogue().then(approved => {
    if (!approved.length) return;
    const urls = new Set((memCache ?? []).map(ch => ch.streamUrl.trim()));
    const additions = approved.filter(ch => {
      const url = ch.streamUrl.trim();
      if (urls.has(url)) return false;
      urls.add(url);
      return true;
    });
    if (!additions.length) return;
    memCache = [...(memCache ?? []), ...additions];
    try { localStorage.setItem(CACHE_KEY, JSON.stringify({ channels: memCache, timestamp: Date.now() })); } catch { /* quota */ }
    window.dispatchEvent(new Event('iptv-channels-updated'));
  }).catch(error => console.warn('[IPTV] Approved catalogue unavailable:', error))
    .finally(() => { approvedRefresh = null; });
}
function startCatalogueDiscovery(): void {
  refreshApprovedCatalogue();
  backgroundRefresh ??= fetchExtraSources().catch(error => {
    console.warn('[IPTV] Optional discovery failed:', error);
  }).finally(() => { backgroundRefresh = null; });
}

const DISCOVERY_INTERVAL_MS = 15 * 60 * 1000;
let discoveryTimer: ReturnType<typeof setInterval> | null = null;
function scheduleBackgroundDiscovery(): void {
  if (typeof window === 'undefined' || discoveryTimer !== null) return;
  discoveryTimer = window.setInterval(() => {
    if (document.visibilityState === 'hidden' || !memCache?.length) return;
    sourceHealth.clear(); // Retry temporarily failing sources on the next discovery cycle.
    startCatalogueDiscovery();
  }, DISCOVERY_INTERVAL_MS);
}

let sourceCursor = 0;
async function fetchExtraSources(): Promise<void> {
  const allSources = [...new Map(EXTRA_SOURCES.map(([tag, url]) => [url, [tag, url] as [string, string]])).values()];
  // Scan a bounded rotating batch rather than keeping thousands of requests
  // running in a browser tab. Subsequent discovery cycles resume where we left off.
  const batchSize = Math.min(80, allSources.length);
  const sources = Array.from({ length: batchSize }, (_, i) => allSources[(sourceCursor + i) % allSources.length]);
  sourceCursor = (sourceCursor + batchSize) % allSources.length;
  const existingIds = new Set((memCache ?? []).map(ch => ch.id.toLowerCase()));
  const existingUrls = new Set((memCache ?? []).map(ch => ch.streamUrl.trim()));
  let cursor = 0;
  let added = 0;
  await Promise.all(Array.from({ length: Math.min(4, sources.length) }, async () => {
    while (cursor < sources.length) {
      const [tag, url] = sources[cursor++];
      // Back off failing sources for the remainder of this session.
      if ((sourceHealth.get(url) ?? 0) >= 2) continue;
      try {
        const response = await fetch(url, { signal: AbortSignal.timeout(6500) });
        if (!response.ok || Number(response.headers.get('content-length') || 0) > MAX_SOURCE_BYTES) throw new Error('Source unavailable or oversized');
        const body = await response.text();
        if (body.length > MAX_SOURCE_BYTES || !body.includes('#EXTINF')) throw new Error('Invalid playlist');
        const parsedChannels = parseM3U(body, tag);
        const batch: IPTVChannel[] = [];
        for (const ch of parsedChannels) {
          const id = ch.id.toLowerCase(), stream = ch.streamUrl.trim();
          if (!browserHls(stream) || !ch.name || ch.name.length < 2 || existingUrls.has(stream)) continue;
          // Preserve alternative stream URLs for the same tvg-id with distinct card keys.
          if (existingIds.has(id)) {
            let suffix = 1;
            while (existingIds.has(`${id}-feed-${suffix}`)) suffix++;
            ch.id = `${ch.id}-feed-${suffix}`;
          }
          existingIds.add(ch.id.toLowerCase()); existingUrls.add(stream); batch.push(ch);
        }
        console.log(`[IPTV] Source ${tag}: parsed ${parsedChannels.length}, accepted ${batch.length}`);
        if (batch.length) {
          memCache = [...(memCache ?? []), ...batch];
          added += batch.length;
          if (typeof window !== 'undefined') window.dispatchEvent(new Event('iptv-channels-updated'));
        }
      } catch (error) {
        sourceHealth.set(url, (sourceHealth.get(url) ?? 0) + 1);
        console.warn('[IPTV] Optional source skipped:', tag, error);
      }
    }
  }));
  console.log('[IPTV] Background ingestion finished:', added, 'additional channels; catalogue total:', memCache?.length ?? 0);
  // Persist the expanded catalogue, not just the smaller primary-only snapshot.
  try {
    if (memCache?.length) localStorage.setItem(CACHE_KEY, JSON.stringify({ channels: memCache, timestamp: Date.now() }));
  } catch { /* Storage quota or privacy mode; in-memory catalogue remains usable. */ }
}

export async function fetchAllChannels(): Promise<IPTVChannel[]> {
  if (memCache?.length) { scheduleBackgroundDiscovery(); startCatalogueDiscovery(); return memCache; }
  scheduleBackgroundDiscovery();
  // Keep expired cache available as a safety net during a potentially partial refresh.
  let previousCache: CacheData | null = null;
  try {
    const raw = localStorage.getItem(CACHE_KEY);
    if (raw) {
      const cached: CacheData = JSON.parse(raw);
      if (Array.isArray(cached.channels) && cached.channels.length > 100 && Number.isFinite(cached.timestamp)) previousCache = cached;
      if (Array.isArray(cached.channels) && Number.isFinite(cached.timestamp) && Date.now() - cached.timestamp < CACHE_TTL && cached.channels.length > 100) {
        memCache = cached.channels;
        startCatalogueDiscovery();
        return memCache;
      }
    }
  } catch { /* Storage can be disabled on some devices. */ }
  try {
    const [chanRes, streamRes] = await Promise.all([
      fetch(CHANNELS_API, { signal: AbortSignal.timeout(12000) }),
      fetch(STREAMS_API, { signal: AbortSignal.timeout(15000) }),
    ]);
    if (!chanRes.ok || !streamRes.ok) throw new Error('Primary API error');
    const rawChannels: RawChannel[] = await chanRes.json();
    const rawStreams: RawStream[] = await streamRes.json();
    const streamMap = new Map<string, string>();
    for (const stream of rawStreams) {
      if (stream.channel && stream.url && browserHls(stream.url) && !streamMap.has(stream.channel)) streamMap.set(stream.channel, stream.url);
    }
    let freshChannels = shuffle(rawChannels.filter(ch => !ch.is_nsfw && ch.name && streamMap.has(ch.id)).map(ch => ({
      id: ch.id, name: ch.name, logo: ch.logo || genLogoUrl(ch.name),
      country: ch.country || 'INT', countryCode: ch.country || 'INT',
      languages: ch.languages || [], categories: ch.categories?.length ? ch.categories : ['general'],
      streamUrl: streamMap.get(ch.id)!, alt_names: ch.alt_names || [], website: ch.website, network: ch.network,
    })));
    // A successful HTTP response can still contain no usable browser streams.
    // Never cache an empty catalogue as success: show the last-known-good or
    // fallback immediately and keep trying optional configured sources.
    if (freshChannels.length === 0) {
      console.warn('[IPTV] Primary returned zero usable HLS channels; recovering catalogue');
      memCache = previousCache?.channels?.length ? previousCache.channels : getFallbackChannels();
      startCatalogueDiscovery();
      return memCache;
    }
    // Reject a refresh that loses more than 35% of a useful prior catalogue.
    if (previousCache && previousCache.channels.length >= 1000 && freshChannels.length < previousCache.channels.length * 0.65) {
      console.warn('[IPTV] Catalogue refresh rejected: unexpected shrink', { previous: previousCache.channels.length, fresh: freshChannels.length });
      freshChannels = previousCache.channels;
    }
    console.log(`[IPTV] Primary: ${rawChannels.length} channel records, ${rawStreams.length} stream records; accepted ${freshChannels.length} playable channels`);
    memCache = freshChannels;
    try { localStorage.setItem(CACHE_KEY, JSON.stringify({ channels: memCache, timestamp: Date.now() })); } catch { /* quota */ }
    startCatalogueDiscovery();
    return memCache;
  } catch (error) {
    console.warn('[IPTV] Primary catalogue unavailable:', error);
    // Prefer the last-known-good catalogue over a tiny fallback when upstream is down.
    memCache = previousCache?.channels?.length ? previousCache.channels : getFallbackChannels();
    startCatalogueDiscovery();
    return memCache;
  }
}

export function getChannelPage(channels: IPTVChannel[], category: string, page: number, countryCode = ''): ChannelPage {
  let filtered = channels.filter(ch => !deadIds.has(ch.id));
  if (category !== 'all') {
    filtered = filtered.filter(ch => ch.categories.some(c => c.toLowerCase() === category.toLowerCase()));
  }
  if (countryCode) {
    filtered = filtered.filter(ch => ch.countryCode.toLowerCase() === countryCode.toLowerCase());
  }
  filtered = prioritizeStreams(filtered);
  const start = (page - 1) * PAGE_SIZE;
  return { items: filtered.slice(start, start + PAGE_SIZE), hasMore: start + PAGE_SIZE < filtered.length, total: filtered.length };
}

